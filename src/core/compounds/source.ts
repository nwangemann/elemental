/** How the card draws it: one molecule, a repeating crystal chunk, a metal ingot, or one atom. */
export type CompoundKind = 'molecule' | 'lattice' | 'alloy' | 'atom';

/** The bond chip: shares electrons, hands one over, metal mix, or none (stays alone). */
export type Bond = 'shares' | 'transfers' | 'metal' | 'none';

/** What one person can carry at once: glucose (24 atoms) fits, sucrose (45) is Show me only. */
export const CARRY_LIMIT = { elements: 5, atoms: 24 } as const;

export const CONTEXTS = ['body', 'air', 'kitchen', 'earth'] as const;
export type Context = (typeof CONTEXTS)[number];

export interface CompoundSource {
  /** Stable id, kebab case: used in links and storage. */
  id: string;
  name: string;
  /** Display formula with subscripts. Alloys list their elements joined by " + ". */
  formula: string;
  /** PubChem name lookup; absent for alloys, which have no single record. */
  pubchem?: string;
  kind: CompoundKind;
  bond: Bond;
  contexts: Context[];
  /** Offered when Combine opens with nothing carried. */
  starter?: true;
  /** One or two steps up the scale ladder, as short phrases. */
  leadsTo: string[];
  /** Where you meet it: one line. */
  where: string;
  /** Why it holds together: one line, every term glossed. */
  why: string;
  /** An extra line when the kind needs explaining (lattice, alloy, lone atom, isomer). */
  note?: string;
  /** For a lattice: where its crystal chunk comes from (see `LatticeSpec`). */
  lattice?: LatticeSpec;
}

/**
 * A lattice's chunk: a Crystallography Open Database entry, the element the chunk is centred
 * on, its radius in Å, and the element pairs drawn as sticks with their longest length.
 */
export interface LatticeSpec {
  cod: string;
  centre: string;
  radius: number;
  bonds: [string, string, number][];
}

